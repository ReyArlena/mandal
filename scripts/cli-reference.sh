#!/usr/bin/env bash
#
# Writes docs/reference/cli-commands.md from `mandal help`, so the command
# table in the docs always matches the CLI in the same checkout.
#
#   bash scripts/cli-reference.sh           # rewrite the file
#   bash scripts/cli-reference.sh --check   # fail when the file is out of date (CI)

set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="$root/docs/reference/cli-commands.md"

render() {
    printf '<!-- Generated by scripts/cli-reference.sh from "mandal help"; do not edit by hand. -->\n\n'
    printf '| Command | What it does |\n|---|---|\n'
    bash "$root/server/bin/mandal" help | awk '
        /^  [a-z]/ {
            name = $1
            sub(/^  [^ ]+ +/, "")
            gsub(/\|/, "\\|")
            gsub(/</, "\\&lt;")
            gsub(/>/, "\\&gt;")
            printf "| `%s` | %s |\n", name, $0
        }'
}

if [[ "${1:-}" == "--check" ]]; then
    if diff -u "$target" <(render) > /dev/null; then
        echo "docs/reference/cli-commands.md is up to date"
    else
        echo "docs/reference/cli-commands.md is out of date; run: bash scripts/cli-reference.sh" >&2
        diff -u "$target" <(render) >&2 || true
        exit 1
    fi
else
    render > "$target"
    echo "wrote ${target#"$root"/}"
fi
